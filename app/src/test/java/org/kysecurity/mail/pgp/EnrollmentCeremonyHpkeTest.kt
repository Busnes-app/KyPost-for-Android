package org.kysecurity.mail.pgp

import kotlinx.coroutines.runBlocking
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.After
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import java.util.Base64

/**
 * v4/v5 envelopes sealed by KyPost-Server's browser sealer (`deviceEnrollment.ts`, `@hpke/core`),
 * generated by `src/test/resources/hpke/seal-with-kypost-server.mjs`. The recipient private key is
 * public test data and opens through software ECDH in place of the Keystore.
 */
class EnrollmentCeremonyHpkeTest {

    private val fixture = Json.parseToJsonElement(
        String(requireNotNull(javaClass.getResourceAsStream("/hpke/browser-sealed-envelopes.json")).use { it.readBytes() }),
    ).jsonObject
    private val skR = unhex(fixture["recipient"]!!.jsonObject["skR"]!!.jsonPrimitive.content)
    private val pkR = Base64.getDecoder().decode(fixture["recipient"]!!.jsonObject["pkR"]!!.jsonPrimitive.content)
    private val deviceId = fixture["deviceId"]!!.jsonPrimitive.content
    private val fingerprint = fixture["fingerprint"]!!.jsonPrimitive.content
    private fun case(version: Int): JsonObject = fixture["cases"]!!.jsonArray.map { it.jsonObject }.single { it["version"]!!.jsonPrimitive.int == version }
    private fun envelope(version: Int) = case(version)["envelope"]!!.jsonPrimitive.content
    private fun plaintext(version: Int) = case(version)["plaintext"]!!.jsonPrimitive.content.toByteArray(Charsets.UTF_8)
    private fun strings(version: Int, name: String) = case(version)[name]!!.jsonArray.map { it.jsonPrimitive.content }

    private val v4Delivery get() = DeliveryMetadata(ENVELOPE_VERSION_HPKE, fingerprint, null, null, null)
    private val v5Delivery get() = DeliveryMetadata(
        ENVELOPE_VERSION_HPKE_KEYRING, fingerprint, case(5)["materialGeneration"]!!.jsonPrimitive.long,
        strings(5, "primaryFingerprints"), strings(5, "keyFingerprints"),
    )

    @After fun cleanup() = EnrollmentSession.clear()

    private fun open(envelope: String, version: Int, deviceId: String = this.deviceId, fingerprint: String = this.fingerprint): ByteArray? {
        val fields = parseDeviceEnvelope(envelope, OPENABLE_ENVELOPE_VERSIONS.toSet()) ?: return null
        return hpkeOpenBase(fields.epk, pkR, deviceEnvelopeAad(version, deviceId, fingerprint), fields.ct, softwareDh(skR))
    }

    @Test
    fun browserSealedEnvelopesOpen() {
        for (version in listOf(ENVELOPE_VERSION_HPKE, ENVELOPE_VERSION_HPKE_KEYRING)) {
            assertEquals(version, parseDeviceEnvelope(envelope(version), OPENABLE_ENVELOPE_VERSIONS.toSet())?.version)
            assertArrayEquals("v$version", plaintext(version), open(envelope(version), version))
        }
    }

    /** info binds version, device and fingerprint; none of them can be swapped after sealing. */
    @Test
    fun browserSealedEnvelopesRefuseAnyOtherBinding() {
        val other = "A".repeat(40)
        for ((version, relabeled) in listOf(4 to 5, 5 to 4)) {
            val env = envelope(version)
            assertNull("relabeled", open(env.replace("\"v\":$version", "\"v\":$relabeled"), relabeled))
            assertNull("other device", open(env, version, deviceId = "dev-1"))
            assertNull("other fingerprint", open(env, version, fingerprint = other))
            val fields = parseDeviceEnvelope(env, OPENABLE_ENVELOPE_VERSIONS.toSet())!!
            assertNull("no info", hpkeOpenBase(fields.epk, pkR, ByteArray(0), fields.ct, softwareDh(skR)))
            assertNull("v2/v3-only caller", parseDeviceEnvelope(env, setOf(ENVELOPE_VERSION_LEGACY, ENVELOPE_VERSION_KEYRING)))
        }
    }

    @Test
    fun hpkeFramingIsStrict() {
        val good = envelope(ENVELOPE_VERSION_HPKE)
        val all = OPENABLE_ENVELOPE_VERSIONS.toSet()
        assertNull("quoted version", parseDeviceEnvelope(good.replace("\"v\":4", "\"v\":\"4\""), all))
        assertNull("legacy alg", parseDeviceEnvelope(good.replace("HPKE-Base-P256-SHA256-A256GCM", "ECDH-P256+HKDF-SHA256+A256GCM"), all))
        assertNull("extra field", parseDeviceEnvelope(good.replace("{\"v\":4,", "{\"v\":4,\"iv\":\"AAAAAAAAAAAAAAAA\","), all))
        assertNull("unpadded enc", parseDeviceEnvelope(good.replace("=\",\"ct\"", "\",\"ct\""), all))
        val offCurve = Base64.getEncoder().encodeToString(ByteArray(65).also { it[0] = 4; it[64] = 1 })
        val enc = Regex("\"enc\":\"([^\"]+)\"").find(good)!!.groupValues[1]
        assertNull("off-curve enc", parseDeviceEnvelope(good.replace(enc, offCurve), all))
    }

    private fun ports(envelope: String, delivery: DeliveryMetadata?, deviceId: String = this.deviceId, identity: String = fingerprint) = FakePorts(
        identityResult = IdentityCheck.ClientProtected(identity),
        deviceIdValue = deviceId,
        fetchResults = mutableListOf(EnrollmentCallResult.Envelope(envelope, delivery)),
        keys = FakeEnrollmentKeys(point = pkR, agree = softwareDh(skR)),
    )

    @Test
    fun aV4DeliveryIsSealedAsLegacyArmorAndAcknowledgedAsLegacy() = runBlocking {
        val ports = ports(envelope(ENVELOPE_VERSION_HPKE), v4Delivery)

        ports.ceremony().run()

        assertEquals(EnrollmentUiState.Enrolled, ports.states.last())
        assertEquals(listOf(VaultRecordKind.LEGACY_ARMOR), ports.sealer.kinds)
        assertArrayEquals(plaintext(ENVELOPE_VERSION_HPKE), ports.sealer.received.single())
        assertEquals(listOf<EnrollmentReport>(EnrollmentReport.Legacy), ports.transport.reported)
        assertEquals(1, ports.keys.deleteCalls)
    }

    @Test
    fun aV5DeliveryIsImportedAndAcknowledgedAsVersion5() = runBlocking {
        val ports = ports(envelope(ENVELOPE_VERSION_HPKE_KEYRING), v5Delivery)

        ports.ceremony().run()

        assertEquals(EnrollmentUiState.Enrolled, ports.states.last())
        assertEquals(listOf(VaultRecordKind.KEYRING), ports.sealer.kinds)
        assertArrayEquals(plaintext(ENVELOPE_VERSION_HPKE_KEYRING), ports.sealer.received.single())
        val ack = EnrollmentReport.Keyring(v5Delivery.materialGeneration!!, fingerprint, ENVELOPE_VERSION_HPKE_KEYRING)
        assertEquals(listOf(ack), ports.sealer.acks)
        assertEquals(listOf<EnrollmentReport>(ack), ports.transport.reported)
    }

    @Test
    fun theExactDeliveryChecksApplyToHpke() = runBlocking {
        val v5 = envelope(ENVELOPE_VERSION_HPKE_KEYRING)
        val cases = listOf(
            ports(v5, null) to FailureReason.ENVELOPE_MALFORMED,
            ports(v5, v5Delivery.copy(version = ENVELOPE_VERSION_KEYRING)) to FailureReason.ENVELOPE_MALFORMED,
            ports(envelope(ENVELOPE_VERSION_HPKE), v5Delivery) to FailureReason.ENVELOPE_MALFORMED,
            ports(v5, v5Delivery.copy(materialGeneration = null)) to FailureReason.ENVELOPE_MALFORMED,
            ports(v5, v5Delivery.copy(materialGeneration = 3L)) to FailureReason.KEYRING_REJECTED,
            ports(v5, v5Delivery.copy(keyFingerprints = strings(5, "keyFingerprints").drop(1))) to FailureReason.KEYRING_REJECTED,
            ports(v5, v5Delivery, deviceId = "dev-1") to FailureReason.COULD_NOT_OPEN,
            ports(envelope(ENVELOPE_VERSION_HPKE), v4Delivery.copy(fingerprint = "A".repeat(40)), identity = "A".repeat(40)) to FailureReason.COULD_NOT_OPEN,
        )
        for ((i, case) in cases.withIndex()) {
            val (ports, reason) = case
            ports.ceremony().run()
            assertEquals("case $i", EnrollmentUiState.Failed(reason), ports.states.last())
            assertEquals(emptyList<VaultRecordKind>(), ports.sealer.kinds)
            assertEquals(emptyList<EnrollmentReport>(), ports.transport.reported)
            assertEquals(1, ports.keys.deleteCalls)
        }
    }
}
